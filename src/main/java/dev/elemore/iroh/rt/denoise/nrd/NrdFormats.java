package dev.elemore.iroh.rt.denoise.nrd;

import static org.lwjgl.vulkan.VK12.*;

/** nrd::Format (NRDDescs.h order) -> VkFormat and bytes per pixel. */
public final class NrdFormats {
    private NrdFormats() {}

    private static final String[] NAMES = {"R8_UNORM", "R8_SNORM", "R8_UINT", "R8_SINT", "RG8_UNORM", "RG8_SNORM", "RG8_UINT", "RG8_SINT", "RGBA8_UNORM", "RGBA8_SNORM", "RGBA8_UINT", "RGBA8_SINT",
            "RGBA8_SRGB", "R16_UNORM", "R16_SNORM", "R16_UINT", "R16_SINT", "R16_SFLOAT", "RG16_UNORM", "RG16_SNORM", "RG16_UINT", "RG16_SINT", "RG16_SFLOAT", "RGBA16_UNORM", "RGBA16_SNORM",
            "RGBA16_UINT", "RGBA16_SINT", "RGBA16_SFLOAT", "R32_UINT", "R32_SINT", "R32_SFLOAT", "RG32_UINT", "RG32_SINT", "RG32_SFLOAT", "RGB32_UINT", "RGB32_SINT", "RGB32_SFLOAT",
            "RGBA32_UINT", "RGBA32_SINT", "RGBA32_SFLOAT", "R10_G10_B10_A2_UNORM", "R10_G10_B10_A2_UINT", "R11_G11_B10_UFLOAT", "R9_G9_B9_E5_UFLOAT"};
    private static final int[] VK = {VK_FORMAT_R8_UNORM, VK_FORMAT_R8_SNORM, VK_FORMAT_R8_UINT, VK_FORMAT_R8_SINT, VK_FORMAT_R8G8_UNORM, VK_FORMAT_R8G8_SNORM, VK_FORMAT_R8G8_UINT,
            VK_FORMAT_R8G8_SINT, VK_FORMAT_R8G8B8A8_UNORM, VK_FORMAT_R8G8B8A8_SNORM, VK_FORMAT_R8G8B8A8_UINT, VK_FORMAT_R8G8B8A8_SINT, VK_FORMAT_R8G8B8A8_SRGB, VK_FORMAT_R16_UNORM,
            VK_FORMAT_R16_SNORM, VK_FORMAT_R16_UINT, VK_FORMAT_R16_SINT, VK_FORMAT_R16_SFLOAT, VK_FORMAT_R16G16_UNORM, VK_FORMAT_R16G16_SNORM, VK_FORMAT_R16G16_UINT, VK_FORMAT_R16G16_SINT,
            VK_FORMAT_R16G16_SFLOAT, VK_FORMAT_R16G16B16A16_UNORM, VK_FORMAT_R16G16B16A16_SNORM, VK_FORMAT_R16G16B16A16_UINT, VK_FORMAT_R16G16B16A16_SINT, VK_FORMAT_R16G16B16A16_SFLOAT,
            VK_FORMAT_R32_UINT, VK_FORMAT_R32_SINT, VK_FORMAT_R32_SFLOAT, VK_FORMAT_R32G32_UINT, VK_FORMAT_R32G32_SINT, VK_FORMAT_R32G32_SFLOAT, VK_FORMAT_R32G32B32_UINT,
            VK_FORMAT_R32G32B32_SINT, VK_FORMAT_R32G32B32_SFLOAT, VK_FORMAT_R32G32B32A32_UINT, VK_FORMAT_R32G32B32A32_SINT, VK_FORMAT_R32G32B32A32_SFLOAT, VK_FORMAT_A2B10G10R10_UNORM_PACK32,
            VK_FORMAT_A2B10G10R10_UINT_PACK32, VK_FORMAT_B10G11R11_UFLOAT_PACK32, VK_FORMAT_E5B9G9R9_UFLOAT_PACK32};

    public static int vkFormat(int nrdFormat) {
        return VK[nrdFormat];
    }

    public static String name(int nrdFormat) {
        return NAMES[nrdFormat];
    }

    public static int bytesPerPixel(int f) {
        String n = NAMES[f];
        if (n.startsWith("R8_")) return 1;
        if (n.startsWith("RG8_") || n.startsWith("R16_")) return 2;
        if (n.startsWith("RGBA16_") || n.startsWith("RG32_")) return 8;
        if (n.startsWith("RGB32_")) return 12;
        if (n.startsWith("RGBA32_")) return 16;
        return 4;
    }
}
